def quat_normalize(q: np.ndarray) -> np.ndarray:
    """Normalize a quaternion [q1, q2, q3, q4] (scalar last)."""
    n = np.linalg.norm(q)
    if n < 1e-12:
        return np.array([0.0, 0.0, 0.0, 1.0])
    return q / n


def quat_to_dcm(q: np.ndarray) -> np.ndarray:
    """
    Convert quaternion [q1, q2, q3, q4] (scalar-last) to DCM.
    DCM rotates from inertial to body frame: v_b = C * v_i
    """
    q1, q2, q3, q4 = q
    C = np.array([
        [q4**2 + q1**2 - q2**2 - q3**2, 2*(q1*q2 + q3*q4), 2*(q1*q3 - q2*q4)],
        [2*(q1*q2 - q3*q4), q4**2 - q1**2 + q2**2 - q3**2, 2*(q2*q3 + q1*q4)],
        [2*(q1*q3 + q2*q4), 2*(q2*q3 - q1*q4), q4**2 - q1**2 - q2**2 + q3**2]
    ])
    return C


def quat_to_euler_321(q: np.ndarray) -> np.ndarray:
    """
    Convert quaternion to 3-2-1 (Yaw-Pitch-Roll) Euler angles [rad].
    Returns [Roll, Pitch, Yaw] matching Simulink output ordering.
    """
    C = quat_to_dcm(q)
    yaw = np.arctan2(C[0, 1], C[0, 0])
    pitch = -np.arcsin(np.clip(C[0, 2], -1.0, 1.0))
    roll = np.arctan2(C[1, 2], C[2, 2])
    return np.array([roll, pitch, yaw])


def quat_multiply(p: np.ndarray, q: np.ndarray) -> np.ndarray:
    """Quaternion multiplication p ⊗ q (scalar-last convention)."""
    p1, p2, p3, p4 = p
    q1, q2, q3, q4 = q
    return np.array([
        p4*q1 + p3*q2 - p2*q3 + p1*q4,
        -p3*q1 + p4*q2 + p1*q3 + p2*q4,
        p2*q1 - p1*q2 + p4*q3 + p3*q4,
        -p1*q1 - p2*q2 - p3*q3 + p4*q4
    ])


def quat_conjugate(q: np.ndarray) -> np.ndarray:
    """Conjugate (inverse for unit quaternion): negate vector part."""
    return np.array([-q[0], -q[1], -q[2], q[3]])


