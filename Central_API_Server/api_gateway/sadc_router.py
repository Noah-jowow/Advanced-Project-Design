def compute_ground_station_pos(time: float, target_idx: int = 0) -> tuple[np.ndarray, np.ndarray]:
    """
    Compute ECI position and velocity of the specified ground station at time t.
    Earth rotation is modeled at sidereal rate OMEGA_EARTH.
    """
    idx = int(np.clip(target_idx, 0, len(GROUND_LAT) - 1))
    lat = GROUND_LAT[idx]
    lon0 = GROUND_LONG[idx]
    lon_i = lon0 + OMEGA_EARTH * time
    
    r_gs = RADIUS_EARTH * np.array([
        np.cos(lat) * np.cos(lon_i),
        np.cos(lat) * np.sin(lon_i),
        np.sin(lat)
    ])
    v_gs = np.cross(np.array([0.0, 0.0, OMEGA_EARTH]), r_gs)
    return r_gs, v_gs


def compute_ground_target_quat_and_rate(r: np.ndarray, v: np.ndarray, time: float, target_idx: int = 0) -> tuple[np.ndarray, np.ndarray]:
    """
    Compute target quaternion and inertial target angular rate for active ground target tracking.
    
    Boresight z_b aligns with line-of-sight vector rho = r_gs(t) - r_sc.
    y_b is perpendicular to line-of-sight and relative velocity.
    x_b completes the right-handed triad: x_b = y_b x z_b.
    """
    r_gs, v_gs = compute_ground_station_pos(time, target_idx)
    rho = r_gs - r
    rho_mag = np.linalg.norm(rho)
    if rho_mag < 1e-3:
        return np.array([0.0, 0.0, 0.0, 1.0]), np.zeros(3)
    
    z_t = rho / rho_mag
    v_rel = v_gs - v
    
    y_t = np.cross(z_t, v_rel)
    y_t_norm = np.linalg.norm(y_t)
    if y_t_norm < 1e-6:
        ref = np.array([0.0, 0.0, 1.0])
        if abs(np.dot(z_t, ref)) > 0.99:
            ref = np.array([0.0, 1.0, 0.0])
        y_t = np.cross(z_t, ref)
        y_t_norm = np.linalg.norm(y_t)
        
    y_t = y_t / y_t_norm
    x_t = np.cross(y_t, z_t)
    x_t = x_t / np.linalg.norm(x_t)
    
    C = np.array([x_t, y_t, z_t])
    tr = np.trace(C)
    q4 = 0.5 * np.sqrt(max(1.0 + tr, 0.0))
    if q4 > 1e-6:
        q1 = (C[1, 2] - C[2, 1]) / (4.0 * q4)
        q2 = (C[2, 0] - C[0, 2]) / (4.0 * q4)
        q3 = (C[0, 1] - C[1, 0]) / (4.0 * q4)
    else:
        q1 = np.sqrt(max((1.0 + C[0, 0] - C[1, 1] - C[2, 2]) / 4.0, 0.0))
        q2 = np.sqrt(max((1.0 - C[0, 0] + C[1, 1] - C[2, 2]) / 4.0, 0.0))
        q3 = np.sqrt(max((1.0 - C[0, 0] - C[1, 1] + C[2, 2]) / 4.0, 0.0))
        
    q_target = quat_normalize(np.array([q1, q2, q3, q4]))
    w_target_inertial = np.cross(rho, v_rel) / (rho_mag ** 2)
    return q_target, w_target_inertial


def compute_nadir_target_quat(r: np.ndarray, v: np.ndarray) -> np.ndarray:
    """Compute nadir-pointing target quaternion (z_b -> nadir, y_b -> -h, x_b -> velocity)."""
    r_hat = r / np.linalg.norm(r)
    h = np.cross(r, v)
    h_hat = h / np.linalg.norm(h)
    
    z_b = -r_hat
    y_b = -h_hat
    x_b = np.cross(y_b, z_b)
    x_b = x_b / np.linalg.norm(x_b)
    
    C = np.array([x_b, y_b, z_b])
    tr = np.trace(C)
    q4 = 0.5 * np.sqrt(max(1.0 + tr, 0.0))
    
    if q4 > 1e-6:
        q1 = (C[1, 2] - C[2, 1]) / (4.0 * q4)
        q2 = (C[2, 0] - C[0, 2]) / (4.0 * q4)
        q3 = (C[0, 1] - C[1, 0]) / (4.0 * q4)
    else:
        q1 = np.sqrt(max((1 + C[0, 0] - C[1, 1] - C[2, 2]) / 4.0, 0.0))
        q2 = np.sqrt(max((1 - C[0, 0] + C[1, 1] - C[2, 2]) / 4.0, 0.0))
        q3 = np.sqrt(max((1 - C[0, 0] - C[1, 1] + C[2, 2]) / 4.0, 0.0))
    
    q = np.array([q1, q2, q3, q4])
    return quat_normalize(q)


def compute_elevation_azimuth(r_sc: np.ndarray, r_gs: np.ndarray) -> tuple[float, float, float]:
    """Compute elevation [deg], azimuth [deg], and slant range [km] from ground station to spacecraft."""
    rho = r_sc - r_gs
    slant_range = np.linalg.norm(rho)
    if slant_range < 1e-6:
        return 90.0, 0.0, 0.0
    
    up = r_gs / np.linalg.norm(r_gs)
    sin_el = np.dot(rho, up) / slant_range
    elevation = float(np.degrees(np.arcsin(np.clip(sin_el, -1.0, 1.0))))
    
    z_earth = np.array([0.0, 0.0, 1.0])
    east = np.cross(z_earth, up)
    east_norm = np.linalg.norm(east)
    if east_norm > 1e-6:
        east = east / east_norm
        north = np.cross(up, east)
        rho_north = np.dot(rho, north)
        rho_east = np.dot(rho, east)
        azimuth = float(np.degrees(np.arctan2(rho_east, rho_north)) % 360.0)
    else:
        azimuth = 0.0
        
    return elevation, azimuth, float(slant_range)


