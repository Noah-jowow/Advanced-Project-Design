"""
SADC (Spacecraft Attitude Dynamics & Control) Router
=====================================================
Pure-Python re-implementation of the SADC_simulink7_done Simulink model.

Port source: SADC_simulink7_done_grt_rtw/SADC_simulink7_done.cpp  (v3.3)
             Generated by Simulink Coder 25.1 (R2025a)

Mathematical Model:
  - Quaternion kinematics:     q_dot = 0.5 * Omega(w) * q
  - Euler's rigid body eq:     I * w_dot = T_gg + T_ctrl - w x (I*w)
  - Gravity gradient torque:   T_gg = (3*mu/|r|^5) * (r_b x (I * r_b))
  - Two-body orbital EOMs:     r_ddot = -mu/|r|^3 * r
  - Earth Sidereal Rotation:   theta_E(t) = omega_E * t
  - Ground Target Tracking:    z_b -> (r_gs(t) - r_sc) / |r_gs(t) - r_sc|
  - LQR state feedback:        T_ctrl = -K * [q_err_1:3; w - w_target]

Intended Simulation Start Time:
  - startTime = 51744.4 s (aligns satellite pass directly over Arizona ground targets)
  - Ground Target 0: Prescott (ERAU Campus, 34.62°N, 112.45°W)
  - Ground Target 1: Sedona / Flagstaff (34.94°N, 111.75°W)
  - Ground Target 2: Verde Valley (34.37°N, 111.45°W)

References:
  - Wertz, J.R. "Space Mission Engineering: The New SMAD", Ch. 19 (Attitude Dynamics)
  - Schaub & Junkins, "Analytical Mechanics of Space Systems", Ch. 3-4
  - Sidi, M.J. "Spacecraft Dynamics and Control", Cambridge, 1997
"""

