@router.post("/simulate")
async def simulate(req: SADCSimRequest):
    """Execute SADC simulation via REST API."""
    sim = SADCSimulation(
        dt=req.dt or 0.01,
        start_time=req.start_time if req.start_time is not None else START_TIME_DEFAULT,
        target_mode=req.target_mode or "ground",
        target_idx=req.target_idx or 0
    )
    if req.q0 is not None:
        sim.q = np.array(req.q0, dtype=float)
    if req.w0 is not None:
        sim.w = np.array(req.w0, dtype=float)
    if req.r0 is not None:
        sim.r = np.array(req.r0, dtype=float)
    if req.v0 is not None:
        sim.v = np.array(req.v0, dtype=float)
    return sim.run(req.duration, req.record_interval or 10)


async def sadc_process_command(data: dict, manager=None, websocket=None) -> dict:
    """Process WebSocket commands for the SADC domain."""
    import asyncio
    
    command = data.get("command")
    sim_data = data.get("data", {})
    
    if command == "simulate":
        duration = float(sim_data.get("duration", 600.0))
        dt = float(sim_data.get("dt", 0.01))
        start_time = float(sim_data.get("start_time", START_TIME_DEFAULT))
        target_mode = str(sim_data.get("target_mode", "ground"))
        target_idx = int(sim_data.get("target_idx", 0))
        record_interval = int(sim_data.get("record_interval", 10))
        
        sim = SADCSimulation(
            dt=dt,
            start_time=start_time,
            target_mode=target_mode,
            target_idx=target_idx
        )
        
        # Apply custom initial conditions if provided
        if "q0" in sim_data:
            sim.q = np.array(sim_data["q0"], dtype=float)
        if "w0" in sim_data:
            sim.w = np.array(sim_data["w0"], dtype=float)
        if "r0" in sim_data:
            sim.r = np.array(sim_data["r0"], dtype=float)
        if "v0" in sim_data:
            sim.v = np.array(sim_data["v0"], dtype=float)
        
        if manager and websocket:
            tgt_name = GROUND_NAMES[target_idx] if target_idx < len(GROUND_NAMES) else "Custom"
            await manager.log(f"[SADC] Initializing simulation: startTime={start_time:.1f}s, duration={duration:.1f}s, dt={dt}s", websocket)
            await manager.log(f"[SADC] Target Control Mode: '{target_mode}' -> {tgt_name}", websocket)
            await manager.log(f"[SADC] Initial orbit: alt={np.linalg.norm(sim.r)-RADIUS_EARTH:.1f} km, |v|={np.linalg.norm(sim.v):.3f} km/s", websocket)
            await manager.log(f"[SADC] Initial pass elevation: {sim.gs_elevation:.1f}°, slant range: {sim.gs_range:.1f} km", websocket)
        
        loop = asyncio.get_event_loop()
        results = await loop.run_in_executor(
            None,
            sim.run,
            duration,
            record_interval
        )
        
        if manager and websocket:
            max_el = max(results["gs_elevation"]) if results["gs_elevation"] else 0.0
            min_rng = min(results["gs_range"]) if results["gs_range"] else 0.0
            await manager.log(f"[SADC] Simulation complete. Peak overpass elevation: {max_el:.1f}°, closest range: {min_rng:.1f} km", websocket)
            await manager.log(f"[SADC] Final pointing error (RPY): [{results['euler_error_r'][-1]:.3f}°, {results['euler_error_p'][-1]:.3f}°, {results['euler_error_y'][-1]:.3f}°]", websocket)
        
        return results
    
    elif command == "reset":
        if manager and websocket:
            await manager.log(f"[SADC] Simulation reset to startTime={START_TIME_DEFAULT}s.", websocket)
        return {"status": "reset", "start_time": START_TIME_DEFAULT}
    
    return {"error": f"Unknown SADC command: {command}"}
